#!/usr/bin/env bash
# ============================================================
#  GPT Image 本地便携版 —— macOS / Linux 一键启动
#  用法：双击（或终端里执行）本文件即可，无需敲命令。
#
#  启动策略（已优化为"解压即用"）：
#    1) 若存在构建产物 dist/，直接启动内置零依赖静态服务器，
#       无需 node_modules、无需联网安装依赖，即开即用。
#    2) 若没有 dist/，回退到开发模式：自动装依赖 -> vite dev。
# ============================================================
set -e

cd "$(dirname "$0")"

echo
echo " ============================================"
echo "   GPT Image 本地便携版  正在启动..."
echo " ============================================"
echo

# ---------- 1. 检查 Node.js ----------
if ! command -v node >/dev/null 2>&1; then
    echo " [错误] 未检测到 Node.js。"
    echo "        本便携版需要 Node.js 18 及以上版本。"
    echo "        请前往 https://nodejs.org 下载安装后，再运行本脚本。"
    echo
    read -r -p "按回车退出..." _
    exit 1
fi

# ---------- 2. 优先使用构建产物（解压即用，无需依赖） ----------
if [ -f "dist/index.html" ]; then
    echo " [就绪] 检测到构建产物 dist/，使用内置静态服务器（免依赖启动）。"
    echo " 正在启动应用并自动打开浏览器..."
    echo " 如未自动弹出请手动访问：http://localhost:5173"
    echo " 提示：在此窗口按 Ctrl+C 即可停止应用。"
    echo
    node server.js
    exit 0
fi

# ---------- 3. 没有构建产物时，回退到开发模式 ----------
echo " [提示] 未检测到构建产物，进入开发模式（首次需要联网安装依赖）。"

# ---------- 3.1 首次运行自动安装依赖 ----------
if [ ! -d "node_modules" ]; then
    echo " [首次运行] 正在安装依赖，请耐心等待（可能需要几分钟）..."
    echo
    npm install
fi

# ---------- 3.2 启动服务并自动打开浏览器 ----------
echo " [完成] 正在启动应用并自动打开浏览器..."
echo " 如未自动弹出请手动访问：http://localhost:5173"
echo
echo " 提示：在此窗口按 Ctrl+C 即可停止应用。"
echo
npm run dev -- --open

exit 0
